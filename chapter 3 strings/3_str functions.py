# 1. len()
# Returns the length of a string.
s = "hello"
print(len(s))  # Output: 5



# 2. lower()
# Converts all characters in a string to lowercase.
s = "Hello"
print(s.lower())  # Output: "hello"



# 3. upper()
# Converts all characters in a string to uppercase.
s = "Hello"
print(s.upper())  # Output: "HELLO"



# 4. strip()
# Removes any leading and trailing whitespace (or specified characters).
s = "  hello  "
print(s.strip())  # Output: "hello"



# 5. replace()
# Replaces occurrences of a substring with another substring.
s = "hello world"
print(s.replace("world", "Python"))  # Output: "hello Python"



# 6. startswith()
# Checks if a string starts with a specified prefix.
s = "hello"
print(s.startswith("he"))  # Output: True



# 7. endswith()
# Checks if a string ends with a specified suffix.
s = "hello"
print(s.endswith("lo"))  # Output: True



# 8. capitalize()
# Converts the first character of the string to uppercase.
s = "hello"
print(s.capitalize())  # Output: "Hello"



# 9. title()
# Capitalizes the first letter of each word in the string.
s = "hello world"
print(s.title())  # Output: "Hello World"



# 10. center()
# Centers the string and pads it with a specified character (default is space).
s = "MODx"
print(s.center(10, "-"))  # Output: "--MODx---"

